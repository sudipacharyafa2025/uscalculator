function applyPatternRules(locale: Locale, text: string): string {
  for (const rule of PATTERNS[locale]) {
    const match = text.match(rule.regex);
    if (!match) continue;
    return rule.replace(...match.slice(1));
  }
  return text;
}

function escapeRegExp(input: string): string {
  return input.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

export function translateCalculatorText(locale: Locale, text: string): string {
  if (locale === "en" || !text) return text;
  const trimmed = text.trim();
  if (!trimmed) return text;
  const leading = text.slice(0, text.indexOf(trimmed));
  const trailing = text.slice(text.indexOf(trimmed) + trimmed.length);

  const phrase = PHRASES[locale][trimmed.toLowerCase()];
  let out = phrase ?? applyPatternRules(locale, trimmed);

  if (!phrase) {
    const tokens = TOKENS[locale];
    const entries = Object.entries(tokens).sort((a, b) => b[0].length - a[0].length);
    for (const [key, value] of entries) {
      const regex = new RegExp(`\\b${escapeRegExp(key)}\\b`, "gi");
      out = out.replace(regex, value);
    }
  }

  return `${leading}${out}${trailing}`;
}
